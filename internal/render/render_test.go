func file(body string) providers.GeneratedFile {
	return providers.GeneratedFile{
		Path:    "ci/out.yml",
		Content: []byte(body + "\n" + render.CustomBlock("#", "")),
		Comment: "#",
		YAML:    true,
	}
}

func plan(t *testing.T, root string, f providers.GeneratedFile, force bool) (render.Planned, []render.Conflict) {
	t.Helper()
	planned, conflicts, err := render.Plan(root, []providers.GeneratedFile{f}, "renvoy.yaml", force)
	if err != nil {
		t.Fatal(err)
	}
	if len(planned) == 1 {
		return planned[0], conflicts
	}
	return render.Planned{}, conflicts
}

func write(t *testing.T, root string, p render.Planned) {
	t.Helper()
	if _, err := render.Write(root, []render.Planned{p}); err != nil {
		t.Fatal(err)
	}
}

func read(t *testing.T, root string) string {
	t.Helper()
	b, err := os.ReadFile(filepath.Join(root, "ci", "out.yml"))
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

func TestGenerationLifecycle(t *testing.T) {
	root := t.TempDir()

	p, c := plan(t, root, file("a: 1"), false)
	if len(c) != 0 || p.Action != render.Create {
		t.Fatalf("first generation: action=%s conflicts=%v", p.Action, c)
	}
	write(t, root, p)
	first := read(t, root)
	if !strings.HasPrefix(first, "# Code generated by Renvoy; DO NOT EDIT.\n# Source: renvoy.yaml\n# Checksum: sha256:") {
		t.Fatalf("missing header:\n%s", first)
	}

	if p, _ = plan(t, root, file("a: 1"), false); p.Action != render.Unchanged {
		t.Fatalf("regeneration action = %s, want unchanged", p.Action)
	}

	// Config changed: the old file is pristine, so it is updated.
	p, c = plan(t, root, file("a: 2"), false)
	if len(c) != 0 || p.Action != render.Update {
		t.Fatalf("changed config: action=%s conflicts=%v", p.Action, c)
	}
	write(t, root, p)

	// The user edits inside the custom block; regeneration keeps it.
	edited := strings.Replace(read(t, root), "# Provider-specific content retained during regeneration.\n", "b: kept\n", 1)
	if err := os.WriteFile(filepath.Join(root, "ci", "out.yml"), []byte(edited), 0o644); err != nil {
		t.Fatal(err)
	}
	p, c = plan(t, root, file("a: 3"), false)
	if len(c) != 0 || p.Action != render.Update {
		t.Fatalf("custom edit should keep the file pristine: action=%s conflicts=%v", p.Action, c)
	}
	write(t, root, p)
	if got := read(t, root); !strings.Contains(got, "a: 3\n") || !strings.Contains(got, "# renvoy:begin custom\nb: kept\n# renvoy:end custom\n") {
		t.Fatalf("custom content lost:\n%s", got)
	}

	// The user edits outside the block: refuse without --force.
	handEdited := strings.Replace(read(t, root), "a: 3", "a: hand", 1)
	if err := os.WriteFile(filepath.Join(root, "ci", "out.yml"), []byte(handEdited), 0o644); err != nil {
		t.Fatal(err)
	}
	if _, c = plan(t, root, file("a: 4"), false); len(c) != 1 || !strings.Contains(c[0].Reason, "edited outside its custom block") {
		t.Fatalf("expected an edit conflict, got %v", c)
	}

	// --force replaces the edit but still keeps the custom block.
	p, c = plan(t, root, file("a: 4"), true)
	if len(c) != 0 || p.Action != render.Overwrite {
		t.Fatalf("force: action=%s conflicts=%v", p.Action, c)
	}
	write(t, root, p)
	if got := read(t, root); !strings.Contains(got, "a: 4\n") || !strings.Contains(got, "b: kept\n") {
		t.Fatalf("force result:\n%s", got)
	}
}

