func TestMalformedCustomBlockIsNeverErased(t *testing.T) {
	cases := map[string]string{
		"unclosed":      "# renvoy:begin custom\nkeep: me\n",
		"stray end":     "# renvoy:end custom\n",
		"two blocks":    "# renvoy:begin custom\n# renvoy:end custom\n# renvoy:begin custom\n# renvoy:end custom\n",
		"invalid yaml":  "# renvoy:begin custom\na: [unclosed\n# renvoy:end custom\n",
		"duplicate key": "# renvoy:begin custom\na: 2\n# renvoy:end custom\n",
	}
	for name, content := range cases {
		t.Run(name, func(t *testing.T) {
			root := t.TempDir()
			if err := os.MkdirAll(filepath.Join(root, "ci"), 0o755); err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(filepath.Join(root, "ci", "out.yml"), []byte(content), 0o644); err != nil {
				t.Fatal(err)
			}
			for _, force := range []bool{false, true} {
				if _, c := plan(t, root, file("a: 1"), force); len(c) != 1 {
					t.Fatalf("force=%v: expected a conflict, got %v", force, c)
				}
			}
		})
	}
}

func TestRefusesSymlinks(t *testing.T) {
	root := t.TempDir()
	outside := t.TempDir()
	if err := os.Symlink(outside, filepath.Join(root, "ci")); err != nil {
		t.Skip("symlinks unavailable:", err)
	}
	if _, c := plan(t, root, file("a: 1"), true); len(c) != 1 || !strings.Contains(c[0].Reason, "symbolic link") {
		t.Fatalf("directory symlink: conflicts = %v", c)
	}

	root = t.TempDir()
	if err := os.MkdirAll(filepath.Join(root, "ci"), 0o755); err != nil {
		t.Fatal(err)
	}
	target := filepath.Join(outside, "victim")
	if err := os.Symlink(target, filepath.Join(root, "ci", "out.yml")); err != nil {
		t.Fatal(err)
	}
	if _, c := plan(t, root, file("a: 1"), true); len(c) != 1 || !strings.Contains(c[0].Reason, "symbolic link") {
		t.Fatalf("dangling file symlink: conflicts = %v", c)
	}
	if _, err := os.Stat(target); err == nil {
		t.Fatal("wrote through a symlink")
	}
}

