// Action is what writing a planned file will do.
type Action string

// Planned actions.
const (
	Create    Action = "create"
	Update    Action = "update"
	Unchanged Action = "unchanged"
	Overwrite Action = "overwrite"
)

// Planned is a fully finalized file ready to compare or write.
type Planned struct {
	Path     string // relative, forward slashes
	Abs      string
	Content  []byte
	Existing []byte // nil when the file does not exist
	Action   Action
	MaxBytes int // largest file the target platform accepts; 0 means no limit

	comment, commentEnd string
	backupPath          string      // set for Overwrite: where the previous content goes
	existingMode        fs.FileMode // permissions of the existing file
}

// Conflict explains why a file cannot be written safely.
type Conflict struct {
	Path   string
	Reason string
	Hint   string
}

func (c Conflict) Error() string { return c.Path + ": " + c.Reason }

// CustomLines counts non-placeholder lines inside a planned file's custom block.
func CustomLines(p Planned) int {
	st := style{p.comment, p.commentEnd}
	lines, ok, err := ExtractCustom(p.Content, st)
	if err != nil || !ok {
		return 0
	}
	placeholder := st.line("Provider-specific content retained during regeneration.")
	n := 0
	for _, l := range lines {
		if t := strings.TrimSpace(l); t != "" && t != placeholder {
			n++
		}
	}
	return n
}

// MaxExistingSize bounds how much of an existing target file is read.
const MaxExistingSize = 4 << 20

// Plan finalizes files against what is on disk under root. It never writes.
// Files that cannot be written safely are returned as conflicts.
func Plan(root string, files []providers.GeneratedFile, source string, force bool) ([]Planned, []Conflict, error) {
	var planned []Planned
	var conflicts []Conflict
	for _, f := range files {
		abs, err := targetPath(root, f.Path)
		if err != nil {
			return nil, nil, err
		}
		existing, mode, err := readExisting(root, f.Path)
		var unsafe *unsafePathError
		if errors.As(err, &unsafe) {
			hint := unsafe.hint
			if hint == "" {
				hint = "Renvoy never writes through symbolic links or over non-regular files"
			}
			conflicts = append(conflicts, Conflict{Path: f.Path, Reason: unsafe.reason, Hint: hint})
			continue
		}
		if err != nil {
			return nil, nil, err
		}
		content, err := Finalize(f, source, existing)
		if err != nil {
			if errors.Is(err, ErrMalformedCustomBlock) {
				conflicts = append(conflicts, Conflict{Path: f.Path, Reason: err.Error(),
					Hint: "fix the custom block: exactly one renvoy:begin custom / renvoy:end custom pair, holding only additions to the generated content; Renvoy will not erase custom content, even with --force"})
				continue
			}
			return nil, nil, err
		}
		p := Planned{Path: f.Path, Abs: abs, Content: content, Existing: existing, comment: f.Comment,
			commentEnd: f.CommentEnd, existingMode: mode, MaxBytes: f.MaxBytes}
		switch {
		case existing == nil:
			p.Action = Create
		case string(existing) == string(content):
			p.Action = Unchanged
		case PristineFile(existing, f):
			p.Action = Update
		case force:
			p.Action = Overwrite
			// Resolve the backup now, so a bad backup path is reported before
			// anything is written.
			backup, err := freeBackupPath(root, f.Path)
			if err != nil {
				reason := err.Error()
				if errors.As(err, &unsafe) {
					reason = unsafe.reason
				}
				conflicts = append(conflicts, Conflict{Path: f.Path, Reason: "cannot back up the existing file: " + reason,
					Hint: "remove or rename the file at the backup path, then run again"})
				continue
			}
			p.backupPath = backup
		default:
			reason := "the file was edited outside its custom block"
			if !IsGenerated(existing, f) {
				reason = "the file exists and was not generated by Renvoy"
			}
			conflicts = append(conflicts, Conflict{Path: f.Path, Reason: reason,
				Hint: "review with `renvoy diff`, move hand-written content into a custom block, or pass --force to replace it (the current file is saved as a .renvoy-backup)"})
			continue
		}
		planned = append(planned, p)
	}
	return planned, conflicts, nil
}

func targetPath(root, rel string) (string, error) {
	if rel == "" || path.IsAbs(rel) || strings.Contains(rel, "\\") || path.Clean(rel) != rel || strings.HasPrefix(rel, "../") || rel == ".." {
		return "", fmt.Errorf("refusing unsafe output path %q", rel)
	}
	return filepath.Join(root, filepath.FromSlash(rel)), nil
}

type unsafePathError struct{ reason, hint string }

func (e *unsafePathError) Error() string { return e.reason }

// checkComponents verifies that no existing component of rel under root is a symlink
// and that every existing parent is a directory.
func checkComponents(root, rel string) error {
	parts := strings.Split(rel, "/")
	cur := root
	for i, part := range parts {
		cur = filepath.Join(cur, part)
		info, err := os.Lstat(cur)
		if errors.Is(err, fs.ErrNotExist) {
			return nil
		}
		if err != nil {
			return err
		}
		if info.Mode()&fs.ModeSymlink != 0 {
			return &unsafePathError{reason: fmt.Sprintf("%s is a symbolic link", strings.Join(parts[:i+1], "/"))}
		}
		last := i == len(parts)-1
		if !last && !info.IsDir() {
			return &unsafePathError{reason: fmt.Sprintf("%s is not a directory", strings.Join(parts[:i+1], "/"))}
		}
		if last && !info.Mode().IsRegular() {
			return &unsafePathError{reason: fmt.Sprintf("%s is not a regular file", rel)}
		}
	}
	return nil
}

func readExisting(root, rel string) ([]byte, fs.FileMode, error) {
	if err := checkComponents(root, rel); err != nil {
		return nil, 0, err
	}
	f, err := os.Open(filepath.Join(root, filepath.FromSlash(rel)))
	if errors.Is(err, fs.ErrNotExist) {
		return nil, 0, nil
	}
	if err != nil {
		return nil, 0, err
	}
	defer func() { _ = f.Close() }()
	info, err := f.Stat()
	if err != nil {
		return nil, 0, err
	}
	data, err := io.ReadAll(io.LimitReader(f, MaxExistingSize+1))
	if err != nil {
		return nil, 0, err
	}
	if len(data) > MaxExistingSize {
		return nil, 0, &unsafePathError{reason: fmt.Sprintf("%s is larger than %d bytes", rel, MaxExistingSize),
			hint: "Renvoy does not read files this large, even with --force; move or shorten the file, then run again"}
	}
	return data, info.Mode().Perm(), nil
}

// Backup records where a replaced file's previous content was saved.
type Backup struct {
	Path, BackupPath string
}

// BackupSuffix is appended to a file replaced by --force to save its previous
// content. Providers ignore files with this suffix.
const BackupSuffix = ".renvoy-backup"

// Result reports what Write did, including when it stops early.
type Result struct {
	Backups []Backup
	Written []Planned
}

// Write writes every planned file that changes, atomically per file. Before an
// Overwrite (a forced replacement of an edited or foreign file) it saves the
// previous content next to the file, so --force never loses data. On error the
// result lists the files already written.
func Write(root string, planned []Planned) (Result, error) {
	var res Result
	backups, err := write(root, planned, &res)
	res.Backups = backups
	return res, err
}

func write(root string, planned []Planned, res *Result) ([]Backup, error) {
	var backups []Backup
	for _, p := range planned {
		if p.Action == Unchanged {
			continue
		}
		if err := checkComponents(root, p.Path); err != nil {
			return backups, fmt.Errorf("%s: %w", p.Path, err)
		}
		dir := filepath.Dir(p.Abs)
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return backups, err
		}
		if err := checkComponents(root, p.Path); err != nil {
			return backups, fmt.Errorf("%s: %w", p.Path, err)
		}
		if p.Action == Overwrite {
			// Re-check the planned backup path: it must still be free and safe.
			rel := p.backupPath
			if err := checkComponents(root, rel); err != nil {
				return backups, fmt.Errorf("%s: %w", p.Path, err)
			}
			if _, err := os.Lstat(filepath.Join(root, filepath.FromSlash(rel))); !errors.Is(err, fs.ErrNotExist) {
				return backups, fmt.Errorf("%s: %s appeared after planning; run again", p.Path, rel)
			}
			// The backup keeps the original permissions, so a private file stays private.
			if err := writeAtomic(dir, filepath.Join(root, filepath.FromSlash(rel)), p.Existing, p.existingMode); err != nil {
				return backups, fmt.Errorf("%s: backing up: %w", p.Path, err)
			}
			backups = append(backups, Backup{Path: p.Path, BackupPath: rel})
		}
		// Rewrites keep the file's permissions; new files are created 0644.
		mode := fs.FileMode(0o644)
		if p.Existing != nil {
			mode = p.existingMode
		}
		if err := writeAtomic(dir, p.Abs, p.Content, mode); err != nil {
			return backups, fmt.Errorf("%s: %w", p.Path, err)
		}
		res.Written = append(res.Written, p)
	}
	return backups, nil
}

// freeBackupPath returns the first backup name for rel that does not exist yet,
// refusing symlinks and non-regular files at the candidate paths.
func freeBackupPath(root, rel string) (string, error) {
	for n := 0; n < 1000; n++ {
		candidate := rel + BackupSuffix
		if n > 0 {
			candidate = fmt.Sprintf("%s%s.%d", rel, BackupSuffix, n)
		}
		if err := checkComponents(root, candidate); err != nil {
			return "", err
		}
		if _, err := os.Lstat(filepath.Join(root, filepath.FromSlash(candidate))); errors.Is(err, fs.ErrNotExist) {
			return candidate, nil
		}
	}
	return "", errors.New("too many existing backups; remove old .renvoy-backup files")
}

// ReplaceWithBackup writes content to path atomically. An existing regular file
// is first saved to a free .renvoy-backup name, whose path is returned, and the
// new file keeps its permissions.
func ReplaceWithBackup(path string, content []byte) (string, error) {
	dir, name := filepath.Split(path)
	if dir == "" {
		dir = "."
	}
	mode := fs.FileMode(0o644)
	backup := ""
	if info, err := os.Lstat(path); err == nil {
		if !info.Mode().IsRegular() {
			return "", fmt.Errorf("%s is not a regular file", path)
		}
		old, err := os.ReadFile(path)
		if err != nil {
			return "", err
		}
		rel, err := freeBackupPath(dir, name)
		if err != nil {
			return "", err
		}
		mode = info.Mode().Perm()
		backup = filepath.Join(dir, rel)
		if err := writeAtomic(dir, backup, old, mode); err != nil {
			return "", fmt.Errorf("backing up: %w", err)
		}
	} else if !errors.Is(err, fs.ErrNotExist) {
		return "", err
	}
	return backup, writeAtomic(dir, path, content, mode)
}

func writeAtomic(dir, target string, content []byte, mode fs.FileMode) error {
	tmp, err := os.CreateTemp(dir, ".renvoy-*.tmp")
	if err != nil {
		return err
	}
	name := tmp.Name()
	defer func() { _ = os.Remove(name) }()
	if _, err := tmp.Write(content); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Chmod(mode); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(name, target)
}
