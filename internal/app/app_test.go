func TestProvidersCapabilitiesVersion(t *testing.T) {
	dir := t.TempDir()
	r := run(t, dir, "providers")
	expectCode(t, r, app.ExitOK)
	for _, name := range registry.Names() {
		if !strings.Contains(r.stdout, name) {
			t.Fatalf("providers output lacks %s:\n%s", name, r.stdout)
		}
	}
	r = run(t, dir, "capabilities", "-p", "github-actions", "--format", "json")
	expectCode(t, r, app.ExitOK)
	var caps struct {
		Provider     string `json:"provider"`
		Capabilities []struct {
			ID      string `json:"id"`
			Support string `json:"support"`
		} `json:"capabilities"`
	}
	if err := json.Unmarshal([]byte(r.stdout), &caps); err != nil || caps.Provider != "github-actions" || len(caps.Capabilities) == 0 {
		t.Fatalf("capabilities JSON: %v\n%s", err, r.stdout)
	}
	r = run(t, dir, "capabilities", "-p", "github-actions")
	expectCode(t, r, app.ExitOK)
	if !strings.Contains(r.stdout, "jobs.retries") || !strings.Contains(r.stdout, "unsupported") {
		t.Fatalf("capabilities text:\n%s", r.stdout)
	}
	r = run(t, dir, "version")
	expectCode(t, r, app.ExitOK)
	if !strings.HasPrefix(r.stdout, "renvoy ") || !strings.Contains(r.stdout, "renvoy.dev/v1alpha1") {
		t.Fatalf("version: %s", r.stdout)
	}
}

// Existing files may come from an untrusted checkout; diff must not print their
// terminal control sequences raw.
func TestDiffEscapesControlCharacters(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "renvoy.yaml"), app.Starter)
	writeFile(t, filepath.Join(dir, ".gitlab-ci.yml"), "hostile: \x1b]0;pwned\x07\x1b[2J\n")
	r := run(t, dir, "diff", "-p", "gitlab")
	expectCode(t, r, app.ExitDiffFound)
	if strings.ContainsAny(r.stdout, "\x1b\x07") {
		t.Fatalf("raw control characters in diff output: %q", r.stdout)
	}
	if !strings.Contains(r.stdout, `-hostile: \u001b]0;pwned\u0007\u001b[2J`) {
		t.Fatalf("diff should show escaped controls:\n%s", r.stdout)
	}
}

