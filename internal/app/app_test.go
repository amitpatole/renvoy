// --force reports where it saved the replaced file.
func TestForcePrintsBackup(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "renvoy.yaml"), app.Starter)
	writeFile(t, filepath.Join(dir, ".gitlab-ci.yml"), "hand: written\n")
	r := run(t, dir, "generate", "-p", "gitlab", "--force")
	expectCode(t, r, app.ExitOK)
	if !strings.Contains(r.stderr, "backup    .gitlab-ci.yml -> .gitlab-ci.yml.renvoy-backup") {
		t.Fatalf("stderr: %s", r.stderr)
	}
	if data, _ := os.ReadFile(filepath.Join(dir, ".gitlab-ci.yml.renvoy-backup")); string(data) != "hand: written\n" {
		t.Fatalf("backup content = %q", data)
	}
}

// Round 10: a bad backup path for one file stops --all --force before anything
// is written, keeping the validate-before-write promise.
func TestForceWritesNothingWhenABackupPathIsUnsafe(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "renvoy.yaml"), app.Starter+bambooKeys)
	writeFile(t, filepath.Join(dir, ".gitlab-ci.yml"), "hand: gitlab\n")
	writeFile(t, filepath.Join(dir, "Jenkinsfile"), "hand: jenkins\n")
	if err := os.Symlink(filepath.Join(t.TempDir(), "victim"), filepath.Join(dir, "Jenkinsfile.renvoy-backup")); err != nil {
		t.Skip(err)
	}
	r := run(t, dir, "generate", "--all", "--force")
	expectCode(t, r, app.ExitUnsafeOverwrite)
	if data, _ := os.ReadFile(filepath.Join(dir, ".gitlab-ci.yml")); string(data) != "hand: gitlab\n" {
		t.Fatal(".gitlab-ci.yml was replaced before the run was refused")
	}
	if _, err := os.Stat(filepath.Join(dir, ".gitlab-ci.yml.renvoy-backup")); err == nil {
		t.Fatal("a backup was written before the run was refused")
	}
	if _, err := os.Stat(filepath.Join(dir, ".github")); err == nil {
		t.Fatal("new files were created before the run was refused")
	}
}

// Round 12: when a write fails partway, the files already written are reported.
func TestPartialWriteIsReported(t *testing.T) {
	if runtime.GOOS == "windows" || os.Geteuid() == 0 {
		t.Skip("needs POSIX permissions and a non-root user")
	}
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "renvoy.yaml"), app.Starter)
	if err := os.MkdirAll(filepath.Join(dir, ".github", "workflows"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.Chmod(filepath.Join(dir, ".github", "workflows"), 0o555); err != nil {
		t.Fatal(err)
	}
	defer func() { _ = os.Chmod(filepath.Join(dir, ".github", "workflows"), 0o755) }()
	r := run(t, dir, "generate", "-p", "gitlab", "-p", "github-actions")
	expectCode(t, r, app.ExitFailure)
	if !strings.Contains(r.stderr, "create    .gitlab-ci.yml") || !strings.Contains(r.stderr, "stopped: the files listed above were written") {
		t.Fatalf("stderr: %s", r.stderr)
	}
}

// Round 14: init --force keeps the replaced file as a backup, with its permissions.
func TestInitForceBacksUp(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "renvoy.yaml")
	writeFile(t, path, "hand-written\n")
	if err := os.Chmod(path, 0o600); err != nil {
		t.Fatal(err)
	}
	r := run(t, dir, "init", "--force")
	expectCode(t, r, app.ExitOK)
	old, err := os.ReadFile(path + ".renvoy-backup")
	if err != nil || string(old) != "hand-written\n" || !strings.Contains(r.stderr, "backup    renvoy.yaml -> renvoy.yaml.renvoy-backup") {
		t.Fatalf("backup %q %v\n%s", old, err, r.stderr)
	}
	if info, _ := os.Stat(path); runtime.GOOS != "windows" && info.Mode().Perm() != 0o600 {
		t.Fatalf("mode %v", info.Mode().Perm())
	}
}
