type result struct {
	code           int
	stdout, stderr string
}

func run(t *testing.T, dir string, args ...string) result {
	t.Helper()
	var out, errb bytes.Buffer
	code := app.Run(args, &out, &errb, dir)
	return result{code, out.String(), errb.String()}
}

func expectCode(t *testing.T, r result, code int) {
	t.Helper()
	if r.code != code {
		t.Fatalf("exit code %d, want %d\nstdout:\n%s\nstderr:\n%s", r.code, code, r.stdout, r.stderr)
	}
}

func writeFile(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestInit(t *testing.T) {
	dir := t.TempDir()
	expectCode(t, run(t, dir, "init"), app.ExitOK)
	data, err := os.ReadFile(filepath.Join(dir, "renvoy.yaml"))
	if err != nil || string(data) != app.Starter {
		t.Fatalf("starter not written: %v", err)
	}
	r := run(t, dir, "init")
	expectCode(t, r, app.ExitUnsafeOverwrite)
	if !strings.Contains(r.stderr, "already exists") {
		t.Fatalf("stderr: %s", r.stderr)
	}
	expectCode(t, run(t, dir, "init", "--force"), app.ExitOK)
}

func TestInitRefusesSymlink(t *testing.T) {
	dir := t.TempDir()
	if err := os.Symlink(filepath.Join(t.TempDir(), "victim"), filepath.Join(dir, "renvoy.yaml")); err != nil {
		t.Skip(err)
	}
	expectCode(t, run(t, dir, "init", "--force"), app.ExitUnsafeOverwrite)
}

// bambooKeys are the only settings the starter lacks for Bamboo, which cannot
// invent project and plan keys.
const bambooKeys = "\nextensions:\n  bamboo:\n    projectKey: PROJ\n    planKey: SERVICE\n"

func TestStarterWorksForEveryProvider(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "renvoy.yaml"), app.Starter+bambooKeys)
	r := run(t, dir, "validate")
	expectCode(t, r, app.ExitOK)
	if !strings.Contains(r.stderr, "renvoy.yaml is valid") {
		t.Fatalf("stderr: %s", r.stderr)
	}
	for _, name := range registry.Names() {
		r := run(t, dir, "generate", "--provider", name, "--dry-run")
		expectCode(t, r, app.ExitOK)
		if !strings.Contains(r.stdout, "Code generated by Renvoy; DO NOT EDIT.") {
			t.Fatalf("%s: no generated output", name)
		}
		if strings.Contains(r.stderr, "error") {
			t.Fatalf("%s: unexpected errors:\n%s", name, r.stderr)
		}
	}
	entries, _ := os.ReadDir(dir)
	if len(entries) != 1 {
		t.Fatalf("--dry-run wrote files: %v", entries)
	}
}

func TestValidateJSON(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "renvoy.yaml"), strings.Replace(app.Starter, "runsOn: linux", "runsOn: plan9", 1))
	r := run(t, dir, "validate", "--format", "json")
	expectCode(t, r, app.ExitInvalidSpec)
	var report struct {
		Valid       bool `json:"valid"`
		Errors      int  `json:"errors"`
		Diagnostics []struct {
			Severity string `json:"severity"`
			Path     string `json:"path"`
			File     string `json:"file"`
			Line     int    `json:"line"`
			Message  string `json:"message"`
		} `json:"diagnostics"`
	}
	if err := json.Unmarshal([]byte(r.stdout), &report); err != nil {
		t.Fatalf("invalid JSON: %v\n%s", err, r.stdout)
	}
	if report.Valid || report.Errors != 1 {
		t.Fatalf("report: %+v", report)
	}
	d := report.Diagnostics[0]
	if d.Severity != "error" || d.Path != "stages[0].jobs[0].runsOn" || d.File != "renvoy.yaml" || d.Line == 0 {
		t.Fatalf("diagnostic: %+v", d)
	}
	if r.stderr != "" {
		t.Fatalf("JSON mode must keep stderr clean: %s", r.stderr)
	}

	writeFile(t, filepath.Join(dir, "renvoy.yaml"), app.Starter)
	r = run(t, dir, "validate", "--format", "json")
	expectCode(t, r, app.ExitOK)
	if !strings.Contains(r.stdout, `"valid": true`) {
		t.Fatalf("stdout: %s", r.stdout)
	}
}

