func TestGenerateLifecycle(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "renvoy.yaml"), app.Starter)
	target := filepath.Join(dir, ".github", "workflows", "my-service.yml")

	r := run(t, dir, "generate", "-p", "github-actions")
	expectCode(t, r, app.ExitOK)
	if !strings.Contains(r.stderr, "create") {
		t.Fatalf("stderr: %s", r.stderr)
	}
	first, err := os.ReadFile(target)
	if err != nil {
		t.Fatal(err)
	}

	r = run(t, dir, "generate", "-p", "github-actions")
	expectCode(t, r, app.ExitOK)
	if !strings.Contains(r.stderr, "unchanged") {
		t.Fatalf("stderr: %s", r.stderr)
	}
	expectCode(t, run(t, dir, "diff", "-p", "github-actions"), app.ExitOK)

	// A config change regenerates a pristine file without --force.
	writeFile(t, filepath.Join(dir, "renvoy.yaml"), strings.Replace(app.Starter, "python:3.12", "python:3.13", 1))
	r = run(t, dir, "diff", "-p", "github-actions")
	expectCode(t, r, app.ExitDiffFound)
	if !strings.Contains(r.stdout, "-      image: python:3.12\n+      image: python:3.13") {
		t.Fatalf("diff:\n%s", r.stdout)
	}
	expectCode(t, run(t, dir, "generate", "-p", "github-actions"), app.ExitOK)

	// A hand edit outside the custom block blocks regeneration.
	edited, _ := os.ReadFile(target)
	writeFile(t, target, strings.Replace(string(edited), "ubuntu-latest", "ubuntu-22.04", 1))
	r = run(t, dir, "generate", "-p", "github-actions")
	expectCode(t, r, app.ExitUnsafeOverwrite)
	if !strings.Contains(r.stderr, "edited outside its custom block") || !strings.Contains(r.stderr, "no files were written") {
		t.Fatalf("stderr: %s", r.stderr)
	}
	r = run(t, dir, "diff", "-p", "github-actions")
	expectCode(t, r, app.ExitDiffFound)
	if !strings.Contains(r.stdout, "+    runs-on: ubuntu-latest") {
		t.Fatalf("diff:\n%s", r.stdout)
	}
	expectCode(t, run(t, dir, "generate", "-p", "github-actions", "--force"), app.ExitOK)
	if got, _ := os.ReadFile(target); bytes.Equal(got, first) {
		t.Fatal("expected the regenerated file to reflect the config change")
	}
	expectCode(t, run(t, dir, "diff", "-p", "github-actions"), app.ExitOK)
}

